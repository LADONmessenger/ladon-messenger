//! Exit-Relay v2 binary.
//!
//! Configuration via environment variables:
//!   LADON_LISTEN              bind addr (default 127.0.0.1:8443)
//!   LADON_HKEM_KEYFILE        path to HKEM secret-key file
//!   LADON_ENTRY_KEYS_FILE     path to JSON map { hop_id: hex32 } of allowed
//!                             entry-relay HMAC keys (B2.2). Required in
//!                             production; fail-closed if unset/empty.
//!   LADON_S2S_SKEW_SEC        timestamp skew (default 120)
//!   LADON_FETCH_SKEW_SEC      fetch timestamp skew (default 120)
//!   LADON_CANARY_FILE         path to canary.json (default ./canary.json)
//!
//! Binary keyfile format (raw, generated by `gen_host_secrets`):
//!     X25519_SK     32 B
//!     KYBER768_SK 2400 B
//!     KYBER768_PK 1184 B   (concatenated; total = 3616 bytes, fixed)

use std::sync::Mutex;

use ladon_relay_core_v2::bloom::ReplayWindow;
use ladon_relay_core_v2::hash::exit_id_from_hkem_pk;
use ladon_relay_core_v2::hkem::HkemKeyPair;
use ladon_relay_core_v2::store::{MailboxStore, RecipientDirectory};

use exit_relay_v2::entry_keys::load_entry_keys;
use exit_relay_v2::{router, ExitState, ReqwestPushClient};

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    tracing_subscriber::fmt::init();

    let listen = std::env::var("LADON_LISTEN").unwrap_or_else(|_| "127.0.0.1:8443".into());
    let s2s_skew_sec = std::env::var("LADON_S2S_SKEW_SEC")
        .ok().and_then(|s| s.parse().ok()).unwrap_or(120u64);
    let fetch_skew_sec = std::env::var("LADON_FETCH_SKEW_SEC")
        .ok().and_then(|s| s.parse().ok()).unwrap_or(120u64);
    // F3/F5: cap on mailbox bytes across all recipients; invalid = no start.
    let mailbox_cap_bytes = exit_relay_v2::config::mailbox_cap_bytes(
        std::env::var("LADON_MAILBOX_CAP_BYTES").ok().as_deref(),
    )?;
    tracing::info!(mailbox_cap_bytes, "mailbox global byte cap");
    let canary_path = std::env::var("LADON_CANARY_FILE")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|_| std::path::PathBuf::from("./canary.json"));

    // HKEM keypair: load if LADON_HKEM_KEYFILE is set and non-empty; otherwise
    // fail-closed in production, generate ephemeral keys in dev only.
    let hkem_keys: HkemKeyPair = match std::env::var("LADON_HKEM_KEYFILE") {
        Ok(p) if !p.is_empty() => {
            let path = std::path::PathBuf::from(&p);
            let kp = ladon_relay_core_v2::hkem::load_keyfile(&path)?;
            tracing::info!(keyfile = %path.display(), "HKEM keypair loaded from disk");
            kp
        }
        _ => {
            // FIX F-RUST-EXIT-004: fail-closed in production, dev-only fallback in debug.
            #[cfg(not(debug_assertions))]
            {
                panic!("LADON_HKEM_KEYFILE not set — production fail-closed. Set this environment variable.");
            }
            #[cfg(debug_assertions)]
            {
                tracing::warn!("no LADON_HKEM_KEYFILE — generating ephemeral HKEM keypair (dev only)");
                HkemKeyPair::generate()
            }
        }
    };
    let pk = hkem_keys.public_key_bytes();
    let exit_id = exit_id_from_hkem_pk(&pk);
    tracing::info!(exit_id = %hex::encode(exit_id.as_bytes()), "exit-relay-v2 starting");

    // B2.2 (2026-05-12): Per-entry HMAC key map.
    // FIX P7-EXIT-07 stays in spirit: fail-closed in production when
    // LADON_ENTRY_KEYS_FILE is unset/empty. Replaces the previous single
    // shared LADON_S2S_HMAC_KEY_HEX. File must be a strict JSON map
    // `{hop_id: hex32}` with mode 0640 or stricter.
    let entry_keys_path = std::env::var("LADON_ENTRY_KEYS_FILE").unwrap_or_default();
    let entry_keys: std::sync::Arc<std::collections::HashMap<String, [u8; 32]>> =
        if !entry_keys_path.is_empty() {
            let m = load_entry_keys(std::path::Path::new(&entry_keys_path))?;
            tracing::info!(
                path = %entry_keys_path,
                entries = m.len(),
                "entry-keys map loaded"
            );
            std::sync::Arc::new(m)
        } else {
            #[cfg(not(debug_assertions))]
            {
                return Err("LADON_ENTRY_KEYS_FILE not set — production fail-closed (B2.2). Set this environment variable.".into());
            }
            #[cfg(debug_assertions)]
            {
                tracing::warn!("no LADON_ENTRY_KEYS_FILE — entry-keys map empty (dev only)");
                std::sync::Arc::new(std::collections::HashMap::new())
            }
        };

    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)?
        .as_secs();

    // Optional outbound push-relay client (Phase 3b). Active iff
    // `LADON_PUSH_RELAY_URL` is set. Then `LADON_PUSH_S2S_KEY` (shared with
    // the push-relay's exit-keys entry for this hop) and, since F43, the
    // push relay's public HKEM key and target id are required: a set URL
    // with any of them missing or invalid stops the start (fail-closed),
    // instead of silently running without push or sending unsealed.
    // `LADON_PUSH_HOP` defaults to "exit1".
    let push: Option<std::sync::Arc<dyn exit_relay_v2::PushClient>> =
        match std::env::var("LADON_PUSH_RELAY_URL").ok().filter(|u| !u.is_empty()) {
            Some(url) => {
                let v = hex::decode(std::env::var("LADON_PUSH_S2S_KEY").unwrap_or_default())?;
                if v.len() != 32 {
                    return Err("LADON_PUSH_S2S_KEY must be 32 bytes (64 hex)".into());
                }
                let mut k = [0u8; 32]; k.copy_from_slice(&v);
                let (push_pk, push_target_id) = exit_relay_v2::config::push_target(
                    std::env::var("LADON_PUSH_HKEM_PK").ok().as_deref(),
                    std::env::var("LADON_PUSH_TARGET_ID").ok().as_deref(),
                )?;
                let hop = std::env::var("LADON_PUSH_HOP").unwrap_or_else(|_| "exit1".into());
                tracing::info!(
                    url = %url,
                    hop = %hop,
                    push_target_id = %hex::encode(push_target_id),
                    "push-relay client configured (sealed requests)"
                );
                Some(std::sync::Arc::new(ReqwestPushClient::new(url, k, hop, push_pk, push_target_id)))
            }
            None => {
                tracing::info!("no LADON_PUSH_RELAY_URL — push integration disabled");
                None
            }
        };

    // P7-EXIT-06 / Addendum A1 §9: per-recipient limit on accepted forwards.
    let forward_recipient_limiter = std::sync::Arc::new(
        ladon_relay_core_v2::ratelimit::IdentityRateLimiter::new()
    );

    // P7-EXIT-03: per-hop S2S nonce store + legacy-accept flag.
    // #28a: default fail-closed. All exit-relays already sign the tagged +
    // nonce S2S pre-image and production env sets this =false explicitly, so a
    // new deploy that omits the var must NOT silently re-open the legacy path.
    let s2s_accept_legacy = std::env::var("LADON_S2S_ACCEPT_LEGACY")
        .ok()
        .map(|s| !matches!(s.trim().to_ascii_lowercase().as_str(), "0" | "false" | "no" | "off"))
        .unwrap_or(false);
    tracing::info!(s2s_accept_legacy, "S2S legacy (no-nonce) accept policy");
    // Addendum A1 §10: HSig usecase tags are mandatory; there is no
    // untagged-accept switch any more (`LADON_RCV2_ACCEPT_LEGACY_HSIG` is gone).
    // P7-RELAY-10: TTL = 2 × skew. F8: capacity follows from the admission
    // cap of /v2/sealed (SEALED_ADMIT_PER_SEC), so at an admitted rate the
    // store never fills; sizes and memory in `S2sNonceStore::for_skew`.
    let s2s_nonce_store = exit_relay_v2::s2s::S2sNonceStore::for_skew(s2s_skew_sec);
    // Fetch-replay guard. TTL is 2 × fetch skew (SRV-11). N3: capacity
    // follows from the verify cap every insert passed (`for_skew`).
    let fetch_replay = exit_relay_v2::verify::FetchReplayStore::for_skew(fetch_skew_sec);
    // Periodic GC of the per-recipient table (every 60 s).
    {
        let fl = forward_recipient_limiter.clone();
        tokio::spawn(async move {
            let mut t = tokio::time::interval(std::time::Duration::from_secs(60));
            t.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
            loop {
                t.tick().await;
                fl.cleanup_expired();
            }
        });
    }

    // P7-EXIT-05: best-effort persistence of the active Bloom bucket.
    // Path comes from env; absent → in-RAM-only (current behaviour).
    let replay_snapshot_path = std::env::var("LADON_REPLAY_SNAPSHOT_PATH").ok();
    let initial_replay = match replay_snapshot_path.as_deref() {
        Some(p) => match ReplayWindow::try_restore_active_from(p, now) {
            Ok(Some(w)) => {
                tracing::info!(path = p, "replay window: active bucket restored from snapshot");
                w
            }
            Ok(None) => {
                tracing::info!(path = p, "replay window: no fresh snapshot, starting empty");
                ReplayWindow::new(now)
            }
            Err(e) => {
                tracing::warn!(path = p, error = %e, "replay window: snapshot read error, starting empty");
                ReplayWindow::new(now)
            }
        },
        None => ReplayWindow::new(now),
    };

    let state = ExitState {
        exit_id,
        hkem_keys,
        directory: RecipientDirectory::new(),
        mailbox: MailboxStore::new().with_global_cap_bytes(mailbox_cap_bytes),
        replay: Mutex::new(initial_replay),
        entry_keys,
        s2s_skew_sec,
        fetch_skew_sec,
        canary_path,
        push,
        s2s_nonce_store,
        fetch_replay,
        s2s_accept_legacy,
        forward_recipient_limiter,
        // P7-RELAY-13: bound in-flight push.notify spawns. 256 outstanding
        // is plenty for typical fan-out (one per inbound forward) but
        // prevents fork-bomb under a sustained burst.
        push_notify_sema: std::sync::Arc::new(tokio::sync::Semaphore::new(256)),
        online: std::sync::Arc::new(exit_relay_v2::online::OnlineTracker::new()),
        notify_debounce: std::sync::Arc::new(exit_relay_v2::online::NotifyDebounce::new()),
        sealed_limits: exit_relay_v2::sealed::SealedLimits::default(),
    }.arc();

    // Addendum A1 §14: expired envelopes are removed even if never fetched
    // (until now expiry ran only lazily inside a fetch). Chunked so the
    // mailbox lock is released between batches of recipients.
    {
        let st = state.clone();
        tokio::spawn(async move {
            let mut t = tokio::time::interval(std::time::Duration::from_secs(300));
            t.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
            loop {
                t.tick().await;
                let evicted = st.mailbox.sweep_expired_chunked(1_024);
                if evicted > 0 {
                    tracing::info!(evicted, "mailbox sweep removed expired envelopes");
                }
                // A2 per-recipient tables: drop windows older than 2 min.
                st.sealed_limits.cleanup_expired();
                // F1 (audit 14.10.): self-minted identities can fill the
                // directory and lock out newcomers. Logged every tick (also
                // at start: the first tick fires at once) so the monitoring
                // agent always has a recent value and alarms on a flood.
                // Counts only — no recipient ids.
                tracing::info!(
                    directory_entries = st.directory.len(),
                    directory_capacity = st.directory.capacity(),
                    "directory fill"
                );
            }
        });
    }

    // P7-EXIT-05: periodic snapshot of the active Bloom bucket.
    if let Some(p) = replay_snapshot_path.clone() {
        let state_for_snap = state.clone();
        let interval_sec: u64 = std::env::var("LADON_REPLAY_SNAPSHOT_INTERVAL_SEC")
            .ok()
            .and_then(|v| v.parse().ok())
            .unwrap_or(30);
        tokio::spawn(async move {
            let mut t = tokio::time::interval(std::time::Duration::from_secs(interval_sec));
            t.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);
            loop {
                t.tick().await;
                let snap_path = p.clone();
                let st = state_for_snap.clone();
                // Snapshot off the runtime — it's a synchronous file
                // write that may briefly hold the replay mutex.
                let res = tokio::task::spawn_blocking(move || {
                    // This is the task that could poison the mutex: a panic in
                    // snapshot_active_to while holding it used to disable every
                    // later forward. Recover instead of propagating.
                    let guard = st.replay.lock().unwrap_or_else(|e| e.into_inner());
                    guard.snapshot_active_to(&snap_path)
                }).await;
                match res {
                    Ok(Ok(_)) => {}
                    Ok(Err(e)) => tracing::warn!(error = %e, "replay snapshot write failed"),
                    Err(e) => tracing::warn!(error = %e, "replay snapshot task panicked"),
                }
            }
        });
    }

    let app = router(state);
    let listener = tokio::net::TcpListener::bind(&listen).await?;
    tracing::info!(addr = %listen, "listening");
    axum::serve(listener, app).await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use ladon_relay_core_v2::hash::exit_id_from_hkem_pk;
    // The loader moved to relay-core (shared with the push relay, A2 stage 2);
    // these tests keep exercising it through the exit's startup path.
    use ladon_relay_core_v2::hkem::{
        load_keyfile as load_hkem_keyfile, KEYFILE_KYBER768_PK_LEN, KEYFILE_KYBER768_SK_LEN,
        KEYFILE_TOTAL_LEN, KEYFILE_X25519_SK_LEN,
    };
    use std::io::Write;

    /// Build the same on-disk byte layout that `gen_host_secrets` writes:
    /// X25519_SK(32) || Kyber768_SK(2400) || Kyber768_PK(1184).
    fn write_keyfile(kp: &HkemKeyPair, path: &std::path::Path) {
        use pqcrypto_traits::kem::{PublicKey as _, SecretKey as _};
        let x_sk: [u8; 32] = kp.x_sk.to_bytes();
        let ky_sk = kp.ky_sk.as_bytes();
        let ky_pk = kp.ky_pk.as_bytes();
        assert_eq!(x_sk.len(), KEYFILE_X25519_SK_LEN);
        assert_eq!(ky_sk.len(), KEYFILE_KYBER768_SK_LEN);
        assert_eq!(ky_pk.len(), KEYFILE_KYBER768_PK_LEN);
        let mut buf = Vec::with_capacity(KEYFILE_TOTAL_LEN);
        buf.extend_from_slice(&x_sk);
        buf.extend_from_slice(ky_sk);
        buf.extend_from_slice(ky_pk);
        let mut f = std::fs::File::create(path).unwrap();
        f.write_all(&buf).unwrap();
    }

    #[test]
    fn loader_roundtrip_preserves_exit_id() {
        let dir = tempfile_dir();
        let path = dir.join("hkem.key");
        let original = HkemKeyPair::generate();
        write_keyfile(&original, &path);

        let loaded = load_hkem_keyfile(&path).expect("loader must succeed on valid keyfile");

        let pk_orig = original.public_key_bytes();
        let pk_load = loaded.public_key_bytes();
        assert_eq!(
            pk_orig, pk_load,
            "loaded HKEM public key must equal original"
        );
        let id_orig = exit_id_from_hkem_pk(&pk_orig);
        let id_load = exit_id_from_hkem_pk(&pk_load);
        assert_eq!(
            id_orig.as_bytes(),
            id_load.as_bytes(),
            "exit_id must be stable across keyfile roundtrip"
        );

        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn loader_rejects_wrong_size() {
        let dir = tempfile_dir();
        let path = dir.join("bad.key");
        std::fs::write(&path, vec![0u8; 100]).unwrap();
        let err = match load_hkem_keyfile(&path) {
            Ok(_) => panic!("loader must reject wrong-size keyfile"),
            Err(e) => e,
        };
        assert!(
            err.contains("wrong size") && err.contains("100") && err.contains("3616"),
            "error message must report observed/expected size, got: {err}"
        );
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn loader_rejects_missing_file() {
        let path = std::path::PathBuf::from("/tmp/ladon-this-file-must-not-exist-xyz789.key");
        let _ = std::fs::remove_file(&path);
        let err = match load_hkem_keyfile(&path) {
            Ok(_) => panic!("loader must reject missing file"),
            Err(e) => e,
        };
        assert!(err.contains("failed to read HKEM keyfile"), "got: {err}");
    }

    fn tempfile_dir() -> std::path::PathBuf {
        let mut p = std::env::temp_dir();
        let nonce: u64 = rand_core::RngCore::next_u64(&mut rand_core::OsRng);
        p.push(format!("ladon-exit-loader-test-{nonce:016x}"));
        std::fs::create_dir_all(&p).unwrap();
        p
    }
}
